import {test,expect} from '@playwright/test'
for(const lang of ['pl','en']){
 test('trip lifecycle, contact rejection and conflict '+lang,async({page,browser})=>{
  const prefix=lang==='en'?'/en':'',en=lang==='en',stamp=Date.now()
  const title='Trip UI '+lang+' '+stamp
  async function register(p:typeof page,suffix:string){
   await p.goto(prefix+'/register')
   await p.locator('[name=email]').fill('trip-ui-'+stamp+suffix+'@example.test')
   await p.locator('[name=password]').fill('Long trip UI password 123!')
   await p.locator('[name=confirmation]').fill('Long trip UI password 123!')
   await p.locator('[type=checkbox]').check()
   await p.locator('[type=submit]').click()
   await expect(p.locator('[name=displayName]')).toBeVisible()
  }
  const button=(pl:string,english:string)=>page.getByRole('button',{name:en?english:pl,exact:true})
  await register(page,'a')
  await page.locator('[name=displayName]').fill('Trip Organizer')
  await page.locator('[name=age]').fill('30')
  await page.locator('[name=languages][value=pl]').check()
  await page.locator('[name=travelStyles][value=trekking]').check()
  await page.locator('#profile [type=submit]').click()
  await expect(page.locator('a[href*="/profiles/"]')).toBeVisible()
  await page.getByRole('link',{name:en?'My trips':'Moje wyprawy',exact:true}).click()
  await page.getByRole('link',{name:en?'Create trip':'Utwórz wyprawę'}).click()
  expect((await (await page.request.get('/api/v1/me/trips')).json()).length).toBe(0)
  await page.locator('[name=title]').fill(title)
  await button('Zapisz szkic','Save draft').click()
  await expect(page).toHaveURL(/edit\?id=/)
  const editUrl=page.url(),id=new URL(editUrl).searchParams.get('id')!
  for(const url of [prefix+'/trips/'+id,(en?'/en/trips/':'/pl/wyprawy/')+id+'/secret-slug']){
   const response=await page.request.get(url,{maxRedirects:0})
   expect(response.status()).toBe(404)
   expect(response.headers().location).toBeUndefined()
  }
  await page.reload()
  await expect(page.locator('[name=title]')).toHaveValue(title)
  await page.goto(prefix+'/my-trips')
  await page.getByRole('link',{name:en?'Edit trip':'Edytuj wyprawę',exact:true}).click()
  await expect(page).toHaveURL(editUrl)
  await page.locator('[name=itinerary]').fill('Walk and explore')
  await page.locator('[name=lookingFor]').fill('Friendly travelers')
  await button('Dodaj lokalizację','Add location').click()
  await page.locator('[name=countryCode]').selectOption('PL')
  await page.locator('[name=city]').fill('Zakopane')
  await button('Dodaj lokalizację','Add location').click()
  await page.locator('[name=countryCode]').nth(1).selectOption('SK')
  await button('W górę','Move up').nth(1).click()
  await expect(page.locator('[name=countryCode]').first()).toHaveValue('SK')
  await page.locator('[name=contentLanguage]').selectOption('en')
  await page.locator('[name=styles][value=trekking]').check()
  await page.locator('[name=dateMode]').selectOption('FLEXIBLE')
  await page.locator('[name=dateFrom]').fill('2027-06-01')
  await page.locator('[name=dateTo]').fill('2027-06-10')
  await page.locator('[name=durationDays]').fill('3')
  await page.locator('[name=targetPeople]').fill('4')
  await page.locator('[name=budgetMin]').fill('100')
  await page.locator('[name=budgetMax]').fill('500')
  await button('Opublikuj','Publish').click()
  await expect(page.getByRole('alert')).toContainText(en?'private contact':'prywatny kontakt')
  await expect(page).toHaveURL(editUrl)
  await button('Opublikuj','Publish').click()
  await expect(page.getByRole('alert')).toContainText(en?'private contact':'prywatny kontakt')
  expect((await (await page.request.get('/api/v1/me/trips')).json()).length).toBe(1)
  await page.getByRole('link',{name:en?'Go to the relevant account section':'Przejdź do właściwej sekcji konta'}).click()
  await expect(page).toHaveURL(/account#contacts$/)
  await page.locator('[name=contactEmail]').fill('private-trip-'+stamp+'@example.test')
  await page.locator('#contacts [type=submit]').click()
  await expect(page.locator('#contacts [role=status]')).toBeVisible()
  await page.goto(editUrl)
  await expect(page.locator('[name=title]')).toHaveValue(title)
  // A second tab saves a newer version. The first tab must keep its input.
  const tab=await page.context().newPage()
  await tab.goto(editUrl)
  await tab.locator('[name=title]').fill(title+' newer')
  await tab.getByRole('button',{name:en?'Save draft':'Zapisz szkic',exact:true}).click()
  await expect(tab.getByRole('status')).toContainText(en?'Saved.':'Zapisano.')
  await page.locator('[name=title]').fill(title+' unsaved')
  await button('Zapisz szkic','Save draft').click()
  await expect(page.getByRole('alert')).toContainText(en?'newer version':'nowsza wersja')
  await expect(page.locator('[name=title]')).toHaveValue(title+' unsaved')
  await button('Wczytaj aktualną wersję','Load current version').click()
  await expect(page.locator('[name=title]')).toHaveValue(title+' newer')
  await tab.close()
  await page.locator('[name=title]').fill(title)
  await button('Opublikuj','Publish').click()
  await expect(page.getByRole('link',{name:en?'Public details':'Publiczne szczegóły'})).toBeVisible()
  const second=await browser.newContext({baseURL:'http://localhost:3000'})
  try{
   const b=await second.newPage()
   await register(b,'b')
   await b.goto(en?'/en/trips':'/pl/wyprawy')
   await b.locator('[name=country]').fill('SK')
   await b.locator('[name=budgetMin]').fill('500')
   await b.locator('[name=budgetMax]').fill('600')
   await b.locator('[name=style]').selectOption('trekking')
   await b.locator('form [type=submit]').click()
   await expect(b.getByRole('link',{name:title,exact:true})).toBeVisible()
   const searchUrl=b.url()
   const copied=await second.request.get(searchUrl)
   const ssr=(await copied.text()).replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'')
   expect(ssr).toContain(title)
   await b.reload()
   await b.getByRole('link',{name:title,exact:true}).click()
   await expect(b).toHaveURL(new RegExp(id+'/'))
   const detailsUrl=b.url()
   const redirect=await b.request.get(prefix+'/trips/'+id,{maxRedirects:0})
   expect(redirect.status()).toBe(301)
   const stale=await b.request.get(detailsUrl.replace(/[^/]+$/,'old-slug'),{maxRedirects:0})
   expect(stale.status()).toBe(301)
   const anonymous=await browser.newContext()
   try{const response=await anonymous.request.get(searchUrl);expect(await response.text()).toContain(title)}finally{await anonymous.close()}

   await expect(b.getByRole('heading',{name:title})).toBeVisible()
   await expect(b.locator('main')).toContainText(en?'Open':'Otwarta')
   const html=await (await b.request.get(prefix+'/trips/'+id)).text()
   expect(html).not.toContain('private-trip-'+stamp)
   expect(html).toContain('rel="canonical"')
   expect(html).toContain('name="description"')
   expect(html).toContain('<title>'+title+' — Travel Buddy</title>')
   const privateHtml=await (await page.request.get(editUrl)).text()
   expect(privateHtml).not.toContain(title)
   page.once('dialog',d=>d.accept())
   await button('Zamknij wyprawę','Close trip').click()
   await expect(page.locator('main')).toContainText(en?'Closed':'Zamknięta')
   await page.goto(prefix+'/my-trips')
   await expect(page.locator('article')).toContainText(en?'Closed':'Zamknięta')
   await b.goto(searchUrl)
   await expect(b.locator('main')).not.toContainText(title)
   await b.goto(detailsUrl)
   await expect(b.getByRole('heading',{name:title})).toBeVisible()
   await expect(b.locator('main')).toContainText(en?'Closed':'Zamknięta')
  }finally{await second.close()}
 })
}
