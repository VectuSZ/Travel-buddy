import { test, expect } from '@playwright/test'

test('profile, private contacts and two independent accounts', async ({page, browser}) => {
 const stamp=Date.now(), email=`profile-${stamp}@example.test`, contact=`contact-${stamp}@example.test`
 const password='Profile testing password 123!'
 async function register(p: typeof page, address:string) {
  await p.goto('/register')
  await p.locator('[name=email]').fill(address)
  await p.locator('[name=password]').fill(password)
  await p.locator('[name=confirmation]').fill(password)
  await p.locator('input[type=checkbox]').check()
  await p.locator('button[type=submit]').click()
  await expect(p).toHaveURL(/\/account$/)
  await expect(p.locator('[name=displayName]')).toBeVisible()
 }
 const profileSubmit=()=>page.locator('form').filter({has:page.locator('[name=displayName]')}).locator('[type=submit]')
 const contactSubmit=()=>page.locator('form').filter({has:page.locator('[name=contactEmail]')}).locator('[type=submit]')
 await register(page,email)
 await expect(page.locator('[name=age]')).toHaveValue('')
 await expect(page.locator('[name=contactEmail]')).toHaveValue('')
 await page.locator('[name=displayName]').fill('Testowy Podróżnik')
 await page.locator('[name=age]').fill('29')
 await profileSubmit().click()
 await expect(page.locator('[role=alert]')).toBeVisible() // missing languages
 await page.locator('[name=languages][value=pl]').check()
 await page.locator('[name=languages][value=de]').check()
 await page.locator('[name=travelStyles][value=trekking]').check()
 await page.locator('[name=bio]').fill('Publiczne bio podróżnika')
 await profileSubmit().click()
 await expect(page.locator('a[href^="/profiles/"]')).toBeVisible()
 const me=await (await page.request.get('/api/v1/me')).json()
 const path='/profiles/'+me.userId
 await page.reload()
 await expect(page.locator('[name=bio]')).toHaveValue('Publiczne bio podróżnika')
 await page.locator('[name=contactEmail]').fill(contact)
 await page.locator('[name=instagramHandle]').fill('https://invalid.test')
 await contactSubmit().click()
 await expect(page.locator('[role=alert]')).toBeVisible()
 await expect(page.locator('[name=contactEmail]')).toHaveValue(contact)
 await page.locator('[name=instagramHandle]').fill('@private_handle')
 await page.locator('[name=whatsappE164]').fill('+48123456789')
 await contactSubmit().click()
 await expect(page.locator('[name=instagramHandle]')).toHaveValue('private_handle')
 await page.reload()
 await expect(page.locator('[name=contactEmail]')).toHaveValue(contact)
 // Stale browser draft must survive a 409 until explicit reload.
 const csrf=await (await page.request.get('/api/v1/auth/csrf')).json()
 const edited=await page.request.patch('/api/v1/me/profile',{headers:{'X-CSRF-TOKEN':csrf.token,Origin:'http://localhost:3000'},data:{version:me.profile.version,bio:'New server bio'}})
 expect(edited.status()).toBe(200)
 await page.locator('[name=bio]').fill('Unsaved draft')
 await profileSubmit().click()
 await expect(page.locator('[role=alert]')).toBeVisible()
 await expect(page.locator('[name=bio]')).toHaveValue('Unsaved draft')
 await page.locator('form button[type=button]').click()
 await expect(page.locator('[name=bio]')).toHaveValue('New server bio')
 const anonymous=await browser.newContext({baseURL:'http://localhost:3000'})
 const other=await anonymous.newPage()
 for(const prefix of ['', '/en']) {
  const response=await other.goto(prefix+path)
  const html=await response!.text()
  expect(html).toContain('Testowy Podróżnik')
  for(const secret of [email,contact,'private_handle','+48123456789']) expect(html).not.toContain(secret)
  expect(html).toContain('noindex')
  await expect(other.locator('h1')).toHaveText('Testowy Podróżnik')
 }
 const pub=await anonymous.request.get('/api/v1'+path)
 const dto=await pub.json()
 expect(Object.keys(dto).sort()).toEqual(['userId','displayName','age','bio','languages','travelStyles'].sort())
 await register(other,`second-${stamp}@example.test`)
 const own=await (await other.request.get('/api/v1/me')).json()
 expect(own.profile).toBeNull()
 const otherCsrf=await (await other.request.get('/api/v1/auth/csrf')).json()
 const forbidden=await other.request.patch('/api/v1/me/profile',{headers:{'X-CSRF-TOKEN':otherCsrf.token,Origin:'http://localhost:3000'},data:{userId:me.userId,role:'ADMIN',version:0,bio:'Intrusion'}})
 expect(forbidden.status()).toBe(400)
 expect((await (await other.request.get('/api/v1'+path)).json()).bio).toBe('New server bio')
 await other.goto(path)
 await expect(other.locator('h1')).toHaveText('Testowy Podróżnik')
 const privateHtml=await (await page.request.get('/account')).text()
 for(const secret of [email,contact,'private_handle','+48123456789']) expect(privateHtml).not.toContain(secret)
 for(const field of ['contactEmail','instagramHandle','whatsappE164']) await page.locator(`[name=${field}]`).fill('')
 await contactSubmit().click()
 await expect.poll(async()=> (await (await page.request.get('/api/v1/me')).json()).hasContact).toBe(false)
 await page.reload()
 await expect(page.locator('[name=contactEmail]')).toHaveValue('')
 await page.getByRole('link',{name:'EN',exact:true}).click()
 await expect(page.locator('h2').first()).toHaveText('Public profile')
 await anonymous.close()
})
