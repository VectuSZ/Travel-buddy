import {test,expect} from '@playwright/test'
test('pagination, copied SSR, validation and metadata',async({page,request})=>{
 await page.goto('/pl/wyprawy?size=1')
 const first=await page.locator('article h2').innerText()
 await page.getByRole('link',{name:'Następna',exact:true}).click()
 await expect(page).toHaveURL(/page=2/)
 await expect(page.locator('article h2')).not.toHaveText(first)
 await page.goBack()
 await expect(page.locator('article h2')).toHaveText(first)
 await page.getByRole('button',{name:/Filtry|Filters/}).click()
   await page.locator('[name=country]').fill('Portug')
   await page.getByRole('option',{name:'Portugalia',exact:true}).click()
 await page.locator('form [type=submit]').click()
 await expect(page).toHaveURL(/country=PT/)
 await expect(page).not.toHaveURL(/page=/)
 await expect(page.locator('article h2')).toHaveText('Discover Portugal')
 await expect(page.locator('article')).toHaveCount(1)
 const html=await (await request.get(page.url())).text()
 expect(html).toContain('noindex,follow')
 expect(html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'')).toContain(await page.locator('article h2').innerText())
 const demo='11111111-1111-4111-8111-111111111111'
 const old=await request.get('/trips/'+demo,{maxRedirects:0})
 expect(old.status()).toBe(301)
 expect(old.headers().location).toBe('/pl/wyprawy/'+demo+'/weekend-w-tatrach')
 for(const url of ['/pl/wyprawy/'+demo+'/old','/pl/wyprawy/'+demo]){
  const r=await request.get(url,{maxRedirects:0});expect(r.status()).toBe(301)
 }
 const detail=await (await request.get('/en/trips/'+demo+'/weekend-w-tatrach')).text()
 expect(detail).toContain('href="'+(process.env.E2E_BASE_URL||'http://localhost:3000')+'/pl/wyprawy/'+demo+'/weekend-w-tatrach"')
 expect(detail).toContain('name="description"')
 expect(detail).toContain('lang="pl"')
 const invalid=await request.get('/pl/wyprawy?budgetMin=2500&budgetMax=2200')
 expect(invalid.status()).toBe(400)
 expect(await invalid.text()).toContain('Nieprawidłowe filtry')
})

for (const en of [false,true]) {
 test('country aliases, filters and language menu '+(en?'EN':'PL'), async({page})=>{
  await page.goto(en?'/en':'/')
  const filters=page.getByRole('button',{name:en?/^Filters/:/^Filtry/})
  await expect(filters).toHaveAttribute('aria-expanded','false')
  await expect(page.locator('.route-summary').filter({hasText:en?'Poland · Europe':'Polska · Europa'}).first()).toBeVisible()
  await filters.click()
  const country=page.getByRole('combobox',{name:en?'Country':'Kraj',exact:true})
  for(const alias of ['Anglia','England','Wielka Brytania','United Kingdom']){
   await country.fill(alias)
   await expect(page.getByRole('option',{name:en?'United Kingdom':'Wielka Brytania',exact:true})).toBeVisible()
  }
  await country.press('ArrowDown')
  await country.press('Enter')
  await page.locator('[name=budgetMin]').fill('100')
  await page.locator('#trip-filters [type=submit]').click()
  await expect(filters).toHaveText(en?'Filters (2)':'Filtry (2)')
  await expect(filters).toHaveAttribute('aria-expanded','false')
  await expect(page).toHaveURL(/country=GB/)
  await filters.click()
  await expect(country).toHaveValue(en?'United Kingdom':'Wielka Brytania')
  const menu=page.locator('header nav button')
  await menu.click()
  await expect(page.locator('#language-options [aria-current]')).toContainText(en?'EN':'PL')
  await menu.press('Escape')
  await expect(menu).toHaveAttribute('aria-expanded','false')
  await menu.click()
  await page.locator('h1').click()
  await expect(menu).toHaveAttribute('aria-expanded','false')
  await menu.click()
  await page.getByRole('link',{name:en?'PL':'EN',exact:true}).click()
  await expect(page.locator('html')).toHaveAttribute('lang',en?'pl':'en')
  await expect(menu).toHaveAttribute('aria-expanded','false')
  expect(new URL(page.url()).searchParams.get('budgetMin')).toBe('100')
  await page.getByRole('button',{name:en?'Filtry (2)':'Filters (2)'}).click()
  await page.locator('#trip-filters button[type=button]').click()
  await expect(page).not.toHaveURL(/country=|budgetMin=/)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 })
}
